## ATTENTION: The program "fastlmmc" should be install. It might require authorization of execution for Linux!!! If your operating system is Windows, the executable file (FastLmmC.exe) should be in the working directory. 

## INPUT:
# (1) "pheno" = File containing the phenotypes. First column, must have column name "variety" and contains the individual ID and the following columns include the phenotype with header names such as "Site.Year.Treatment.Trait" (ex.: "biogai.2012.drought.plantHT") so that the column names are self informative. Use exactly this format for the column names. If you do not have year or treatments write for ex. "biogai.NoYear.NoTreatment.plantHT".

# (2) "kin" = RRM (e.g. IBD kinship) or empirical covariance matrix. Kinship should be symetrical (this function will check for you if the kinship is positive-definite). The class of this file is "list" and each element of the list is "matrix".

# (3) geno.file = Binary files without the chr Nb and the extension (i.e. .bed/.bim/.fam generated by plink) containing the genotypes. The three files in the folder "Results_plink" must have the same file name except the extension 
#(ex: "Matrix_Chr1.bed", "Matrix_Chr1.bim", "Matrix_Chr1.fam")

# (4) chr = Nb of chromosome present in the SNP info file (in maize: chr=10 or chr=11 if there are unplaced SNPs put in a fictive chr11).

# (5) type.analysis = Type of analysis to be written in the log file. Ex: "Linear mixed model in FASTLMM for GWAS using a test data set and Rincent et al. 2014 approach"


## Rq1: Markers in the genotyping file are in an increasing order in term of the physical position on the genome and SNPs have unique position

## Rq2: Missing data (NA) are allowed in the phenotypic file and in the genotypic file but fastlmm does a very poor imputation job as the missing SNP values will be mean imputed. I recommand to infer missing data with Beagle or another software.

## Rq3: ATTENTION; THE PHENO, GENO AND KINSHIP MUST HAVE THE SAME INDIVIDUAL NAME AND IN THE SAME ORDER

## OUTPUT:
# (1) Phenotypic files specifically formatted for fastlmmc
# (2) kinship matrices specifically formatted for fastlmmc
# (3) Creation of a "Results" folder with all the GWAS results from fastlmm for each situtaion (one env., one year, one treatment) and each trait. For the description of the columns, see FaST-LMM Manual
# (4) Creation of a "Log" folder which will includes user details on each run of this script

## REFERENCE:
# Lippert et al. (2011). FaST Linear Mixed Models for Genome-Wide Association Studies.     Nature Methods, 8, 833–835
#
# Rincent et al. (2014). Recovering Power in Association Mapping Panels with Variable Levels of Linkage Disequilibrium. Genetics, vol. 197 no. 1 375-387.
###########################################################################################

gwas.fastlmm <- function(pheno, pheno.file, kin, kin.file, geno.file, chr, type.analysis,path){
	# create the folder "FASTLMM"
	dir.create("FASTLMM")
	# create the following result folder in the working directory
	dir.create("./FASTLMM/Results_FASTLMM")
	# Create a temporary result folder "Temp_Results"
	dir.create("./FASTLMM/Temp_Results")
	# Create a log (record) folder
	dir.create("./FASTLMM/Log_FASTLMM")

	pheno = as.data.frame(pheno)



	##############################################################################
	### Create the phenotypic files specifically formatted for fastlmmc for all env.
	##############################################################################
	for(i in 2:length(names(pheno))){
		trait = pheno[,i] # column of the trait you want to analyse
		trait[is.na(trait)] = -9  # replace the missing pheno by "-9" so fastlmm recognizes them as NA

		pheno.fastlmm = cbind(seq(1, nrow(pheno)), pheno$variety, trait)
		colnames(pheno.fastlmm)=c("FID", "IID", names(pheno)[i])

		write.table(pheno.fastlmm, file=paste0("./FASTLMM/FASTLMM_pheno_", names(pheno)[i],".txt"), sep="\t", col.names=TRUE, row.names=FALSE, quote=FALSE)
	}


	###############################################################
	### Create the kinship files specifically formatted for fastlmm
	###############################################################
	for(j in 1:length(kin)){
		rownames(kin[[j]]) = paste(seq(1, nrow(kin[[j]])), rownames(kin[[j]]), sep=" ")
		colnames(kin[[j]]) = paste(seq(1, ncol(kin[[j]])), colnames(kin[[j]]), sep=" ")
	}

	# Check that the kinship matrices are positive definite. The package corpcor should be loaded
	kinship=list()
	for(j in 1:length(kin)){
		if(is.positive.definite(kin[[j]]) == FALSE){
			print("Kinship is not positive definite: converting it") 
			kin[[j]] = make.positive.definite(kin[[j]])
		}
		# Add "var" on the top left of the matrix
		kin = as.matrix(kin)
		var = c("var", colnames(kin[[j]]))
		kinship[[j]] = cbind(rownames(kin[[j]]), kin[[j]])
		kinship[[j]] = rbind(as.vector(var), kinship[[j]])
	
		write.table(kinship[[j]], file=paste0("./FASTLMM/FASTLMM_kinship_sansChr", j,".txt"), sep="\t", col.names=FALSE, row.names=FALSE, quote=FALSE)

	}





	################################
	## GWAS with FASTLMM (REML) 
	################################

# fastlmmc will search for the binary files .bed, .bim, .fam

	for(j in 2:length(names(pheno))){
		resultat = NULL
		fastlmm.pheno = paste0("./FASTLMM/FASTLMM_pheno_", names(pheno)[j], ".txt")
		
		for(i in 1:chr){
			fastlmm.kin = paste0("./FASTLMM/FASTLMM_kinship_sansChr", i, ".txt")
			fastlmm.out = paste0("./FASTLMM/Temp_Results/Temp_RESULTS_FASTLMM_", names(pheno)[j], "_Chr", i, ".csv")

			
			# Calling fastlmm from R
			if(Sys.info()[["sysname"]] == "Linux"){
				#path="/home/snicolas/00_Dossier_Pro/03_Prod_Scien/Cours/GWASPipe/NewPipelineTest/Pipeline_Sandra/PROGRAM/fastlmmc"
			  #command.fastlmm = paste0("fastlmmc -REML -verboseOut -bfile ", paste0(geno.file, i), " -pheno ", fastlmm.pheno, " -sim ", fastlmm.kin, " -simLearnType Full -out ", fastlmm.out)  # Here you force fastlmmc to use your own kinship matrice with the "-sim" option
			  #i=1
				if(length(path)>0){
  			  command.fastlmm = paste0(path," -REML -verboseOut -bfile ", paste0(geno.file, i), " -pheno ", fastlmm.pheno, " -sim ", fastlmm.kin, " -simLearnType Full -out ", fastlmm.out)  # Here you force fastlmmc to use your own kinship matrice with the "-sim" option
  				}else{
  			  command.fastlmm = paste0("fastlmmc -REML -verboseOut -bfile ", paste0(geno.file, i), " -pheno ", fastlmm.pheno, " -sim ", fastlmm.kin, " -simLearnType Full -out ", fastlmm.out)  # Here you force fastlmmc to use your own kinship matrice with the "-sim" option
  				}
  			  # Rq: if you use RStudio, you might have an error message saying that fastlmm is not found. You have to specify the path to fastlmm. To know the path, type the following command in the terminal: "which fastlmmc"
        # command.fastlmm = paste0("/usr/local/bin/fastlmmc -REML -verboseOut -bfile ", paste0(geno.file, i), " -pheno ", paste0("./FASTLMM/FASTLMM_pheno_", names(pheno)[j], ".txt"), " -sim ", paste0("./FASTLMM/FASTLMM_kinship_sansChr", i, ".txt"), " -simLearnType Full -out ", paste0("./FASTLMM/Temp_Results/Temp_RESULTS_FASTLMM_", names(pheno)[j], "_Chr", i, ".csv"))
				system(command.fastlmm, intern=FALSE)
			}

			if(Sys.info()[["sysname"]] == "Windows"){
					command.fastlmm = paste0("FastLmmC -REML -verboseOut -bfile ", paste0(geno.file, i), " -pheno ", fastlmm.pheno, " -sim ", fastlmm.kin, " -simLearnType Full -out ", fastlmm.out)
					
					shell(command.fastlmm)
			}	
				
			res = read.table(file=paste0("./FASTLMM/Temp_Results/Temp_RESULTS_FASTLMM_", names(pheno)[j], "_Chr", i, ".csv"), sep=",", header=TRUE, stringsAsFactors=FALSE)
			resultat = rbind(resultat, res)
		}

	
		colnames(resultat) = colnames(res)

		write.table(resultat, file=paste0("./FASTLMM/Results_FASTLMM/RESULTS_FASTLMM_", names(pheno)[j], "_AllsansChrom.csv"), sep=",", col.names=TRUE, row.names=FALSE, quote=FALSE)

		
		### Log information
		log = rbind(as.character(Sys.time()), type.analysis, names(pheno)[j], "INPUT FILES:", pheno.file, kin.file, geno.file, paste("Nb of individuals analysed:", resultat$N[1], sep=" "), paste("Nb of markers used:", nrow(resultat), sep=" "), paste("Nb of chromosomes:", chr, sep=" "), paste("FASTLMM options:", command.fastlmm, sep=" "))

		write.table(log, file=paste0("./FASTLMM/Log_FASTLMM/Log_", names(pheno)[j], ".txt"), sep="\t", row.names=FALSE, col.names=FALSE, quote=FALSE)
	}

	### Delete the "Temp_Results" folder with the intermediate result files
	if(Sys.info()[["sysname"]] == "Linux"){system("rm -rf ./FASTLMM/Temp_Results")}
	#if(Sys.info()[["sysname"]] == "Windows"){shell("del /s FASTLMM/Temp_Results"); shell("o")}
	

}



